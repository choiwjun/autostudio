# 엔진(get_ganji)은 한자 기둥(丁巳)을 반환 — 한글 키로 변환 매핑
_HANJA_GAN = {'甲': '갑', '乙': '을', '丙': '병', '丁': '정', '戊': '무',
              '己': '기', '庚': '경', '辛': '신', '壬': '임', '癸': '계'}
_HANJA_BRANCH = {'子': '자', '丑': '축', '寅': '인', '卯': '묘', '辰': '진',
                 '巳': '사', '午': '오', '未': '미', '申': '신', '酉': '유',
                 '戌': '술', '亥': '해'}


def to_hangul_pillar(pillar):
    """한자 기둥('丁巳') → 한글('정사'). 이미 한글이면 그대로."""
    if len(pillar) == 2 and pillar[0] in _HANJA_GAN and pillar[1] in _HANJA_BRANCH:
        return _HANJA_GAN[pillar[0]] + _HANJA_BRANCH[pillar[1]]
    return pillar

