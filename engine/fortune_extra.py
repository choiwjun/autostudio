_FIELD_NAMES = ('재물', '애정', '건강', '일')


def field_fortunes(day_gan, year, month, day):
    """일간 오행 × 4분야 문구 (날짜 해시로 결정적 선택).
    반환: {'재물': str, '애정': str, '건강': str, '일': str}"""
    element = _GAN_ELEMENT.get(day_gan, '목')
    result = {}
    for field in _FIELD_NAMES:
        pool = FIELD_PHRASES.get((element, field), [])
        if not pool:
            result[field] = ''
            continue
        idx = (year * 10000 + month * 100 + day) % len(pool)
        result[field] = pool[idx]
    return result


