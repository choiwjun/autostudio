# intent.py — v10: 키워드 의도 분류 (애드포스트 수익 최적화 배치 [1])
# 의도별로 문서 템플릿을 분리해 유입/체류/CPC 변수를 각각 노린다.
#   정보형   → 완결답변형 (AI브리핑 인용 목표, 유입)
#   비교형   → 비교표+결론 기준형 (유입+체류)
#   구매형   → 체크리스트+함정 경고형 (CPC 직결)
import re


class Intent:
    INFO = "info"      # 정보형
    COMPARE = "compare"  # 비교형
    PURCHASE = "purchase"  # 구매 판단형


# 우선순위: 구매 > 비교 > 정보 (키워드가 여러 신호를 가지면 수익 기여가 큰 쪽으로)
# v10.1: '추천 방법/기준'은 정보형, '가격/얼마'는 구매형이 되도록 조정
_PURCHASE_RE = re.compile(
    r"가격|비용|요금|후기|리뷰|구매|구입|할인|이벤트|혜택|얼마|어디서|"
    r"어느\s*회사|어떤\s*제품|무엇을\s*살|사고\s*싶|쿠팡|다이소|가성비|비싸"
)
# v14: 'vs'는 단어 경계(\b) 대신 영문자 옆에만 없으면 매치 — 기존 \b는 한글 인접 시
# 양쪽 모두 단어 문자라 경계가 성립하지 않아 "노트북vs맥북"이 정보형으로 빠지던 버그.
# (classify가 공백을 유지하므로 \s* 허용 패턴도 그대로 동작)
_COMPARE_RE = re.compile(
    r"비교|(?<![a-z])vs(?![a-z])|차이|대비|장단점|어떤\s*게|무엇이|뭐가|"
    r"와\s*비교|대해서|어느\s*것|추천\s*순위|추천\s*비교"
)
_INFO_RE = re.compile(
    r"방법|이유|원인|효과|정의|과정|절차|하는\s*법|하는법|가이드|"
    r"준비|팁|사용법|관리|주의|기준|추천\s*방법|추천\s*기준|하는\s*이유"
)


def classify(keyword):
    """키워드 문자열을 의도로 분류한다. 매치 없으면 정보형(기본)."""
    # v14: 공백 제거 중단 — 제거 시 \b·\s* 경계가 망가져 비교형 오판별이 생겼음.
    # 패턴들이 \s*로 공백을 허용하므로 제거 없이도 매칭됨.
    k = (keyword or "").lower()
    if _PURCHASE_RE.search(k):
        return Intent.PURCHASE
    if _COMPARE_RE.search(k):
        return Intent.COMPARE
    return Intent.INFO


INTENT_NAMES = {
    Intent.INFO: "정보형",
    Intent.COMPARE: "비교형",
    Intent.PURCHASE: "구매형",
}


def intent_template(intent):
    """의도별 문서 템플릿 규칙 (draft 프롬프트에 주입되는 추가 지시)."""
    if intent == Intent.COMPARE:
        return (
            "## 문서 템플릿: 비교형\n"
            "1. 첫문단: 어떤 기준으로 비교해야 하는지 결론부터 제시\n"
            "2. 본문: 항목별 비교표(markdown table) 2개 이상 — 가격/성능/기간 등\n"
            "3. 각 비교 항목에 '어떤 상황에 맞는지' 선택 기준을 함께 제시\n"
            "4. 마지막: 상황별 추천 결론 (예: 1인 가구라면 A, 가족이라면 B)\n"
            "5. FAQ는 'A와 B의 차이는 무엇인가요?' 형태로 구성"
        )
    if intent == Intent.PURCHASE:
        return (
            "## 문서 템플릿: 구매 판단형\n"
            "1. 첫문단: 구매 전 반드시 확인할 핵심 체크포인트 즉답\n"
            "2. 본문: 구매 체크리스트 + 흔한 함정/주의점 (실제 손해 사례 중심)\n"
            "3. 가격·비용 정보는 '통상', '보통' 단위로 표현 (검증된 수치가 아니면 구체적 금액 창작 금지)\n"
            "4. 신중한 구매를 돕는 내용 — 무조건 추천이 아닌 조건부 추천\n"
            "5. FAQ는 '가격이 비싼데 살 만한가요?' 형태로 구성"
        )
    return (
        "## 문서 템플릿: 정보형\n"
        "1. 첫문단: 검색 질문에 완결된 답을 50~200자로 즉답 (AI브리핑 인용 목표)\n"
        "2. 본문: 방법/이유/효과를 단계·순서로 설명 (1단계, 2단계...)\n"
        "3. 각 단계에 왜 해야 하는지 근거를 함께 제시\n"
        "4. FAQ는 '~하는 방법은?' '~의 효과는?' 형태로 구성"
    )
